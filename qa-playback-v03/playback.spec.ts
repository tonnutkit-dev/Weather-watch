import { test, expect } from '@playwright/test';
test('real automatic Play/Pause, scrub, sheet, theme and budget on mobile', async ({ page }, info) => {
  const errors: string[] = [], requests: number[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/rainviewer\.com\/.*\.png/.test(r.url())) requests.push(Date.now()); });
  await page.addInitScript(() => {
    const frames: number[] = []; let last = performance.now();
    function sample(now: number) { frames.push(now-last); last=now; if(frames.length>20000) frames.shift(); requestAnimationFrame(sample); }
    requestAnimationFrame(sample); (window as unknown as { __playbackFrames: number[] }).__playbackFrames = frames;
  });
  await page.goto('./');
  await expect(page.getByTestId('temperature')).toHaveText(/\d+°C/, { timeout: 45000 });
  await expect(page.locator('.map-canvas')).toHaveAttribute('data-map-status', 'ready', { timeout: 30000 });
  await expect(page.getByTestId('radar-presentation')).toHaveAttribute('data-status', 'unverified', { timeout: 40000 });
  const canvas = await page.locator('.maplibregl-canvas').elementHandle();
  const before = await page.getByTestId('radar-time').getAttribute('datetime'); const start = Date.now();
  await page.getByRole('button', { name: 'เล่นเรดาร์ย้อนหลัง', exact: true }).click();
  await expect(page.getByRole('button', { name: 'หยุดเรดาร์', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByTestId('radar-playback')).toContainText('เล่น');
  await expect.poll(() => page.getByTestId('radar-time').getAttribute('datetime'), { timeout: 2000, intervals: [50] }).not.toBe(before);
  const firstMs = Date.now()-start;
  await info.attach('automatic-play-mobile', { body: await page.screenshot(), contentType: 'image/png' });
  const first = await page.getByTestId('radar-time').getAttribute('datetime');
  await expect.poll(() => page.getByTestId('radar-time').getAttribute('datetime'), { timeout: 25000 }).not.toBe(first);
  await page.getByRole('button', { name: 'หยุดเรดาร์', exact: true }).click();
  const paused = await page.getByTestId('radar-time').getAttribute('datetime');
  await page.waitForTimeout(6500); expect(await page.getByTestId('radar-time').getAttribute('datetime')).toBe(paused);
  const slider = page.getByRole('slider', { name: 'เฟรมเรดาร์ย้อนหลัง', exact: true }); await slider.focus(); await slider.press('End');
  expect(await page.getByTestId('radar-time').getAttribute('datetime')).not.toBe(paused);
  await expect(page.getByRole('button', { name: 'เล่นเรดาร์ย้อนหลัง', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'เล่นเรดาร์ย้อนหลัง', exact: true }).click();
  await page.getByRole('button', { name: 'ขยายแผง', exact: true }).click();
  await page.getByRole('button', { name: 'ขยายแผง', exact: true }).click();
  await page.getByRole('button', { name: 'ยุบแผง', exact: true }).click();
  await page.getByRole('button', { name: 'ยุบแผง', exact: true }).click();
  await expect(page.getByRole('button', { name: 'หยุดเรดาร์', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'การแสดงผลและตั้งค่า', exact: true }).click();
  await page.getByRole('button', { name: 'มืด', exact: true }).click(); await page.getByRole('button', { name: 'ปิด', exact: true }).click();
  await expect(page.locator('.map-canvas')).toHaveAttribute('data-theme', 'dark', { timeout: 30000 });
  await page.getByRole('button', { name: 'หยุดเรดาร์', exact: true }).click();
  await expect(page.getByTestId('radar-time')).toContainText('เลือก');
  expect(await page.locator('.map-canvas').getAttribute('data-radar-displayed-frame')).toBe('');
  expect(await page.evaluate(node => node === document.querySelector('.maplibregl-canvas'), canvas)).toBe(true);
  const frames = await page.evaluate(() => (window as unknown as { __playbackFrames: number[] }).__playbackFrames);
  const sorted = frames.filter(v=>v<1000).sort((a,b)=>a-b);
  const peak = Math.max(0,...requests.map(t=>requests.filter(v=>v>t-60000&&v<=t).length)); expect(peak).toBeLessThanOrEqual(80);
  await info.attach('playback-live-measurements', { body: Buffer.from(JSON.stringify({ baseURL: info.project.use.baseURL, firstSelectedFrameMs: firstMs, requestCount: requests.length, peakRolling60s: peak, frameIntervals: { count: frames.length, p95Ms: sorted[Math.floor(sorted.length*0.95)], excludedOver1000ms: frames.length-sorted.length }, sameCanvas: true, errors, note:'Transport readiness is qualified only; selected time is not confirmed pixels. Linux Chromium emulation, not physical iPhone.' },null,2)), contentType:'application/json' });
  await info.attach('paused-dark-mobile', { body: await page.screenshot(), contentType: 'image/png' });
  expect(errors).toEqual([]);
});

